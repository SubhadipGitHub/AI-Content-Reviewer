import { readFileSync, writeFileSync } from 'node:fs';
const names = `scan-search shield-check shield-alert file-text file-image file-code file-archive file-spreadsheet file-type
file-audio file-video file-question file sparkles bot upload-cloud folder-open library sun moon help-circle download
trash-2 x check alert-triangle info search filter chevron-right chevron-down chevron-left image code-2 archive sheet
presentation settings refresh-cw play eye lock wifi-off smartphone monitor zap layers fingerprint badge-check
external-link copy arrow-right history hard-drive cpu wand-2 book-open life-buoy rocket plus clock file-search scan-line
circle-help octagon-alert circle-check-big menu home flask-conical share list-filter`.split(/\s+/);
const out = {};
for (const n of names) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${n}.svg`, 'utf8');
  out[n] = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s*\n\s*/g, '').trim();
}
writeFileSync('src/ui/icon-paths.js', `// Generated by scripts/build-icons.mjs from lucide-static (ISC license, https://lucide.dev). Do not edit.\nexport default ${JSON.stringify(out, null, 0).replace(/","/g, '",\n"')};\n`);
console.log(Object.keys(out).length, 'icons');
