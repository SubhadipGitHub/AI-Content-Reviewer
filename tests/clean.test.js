import { describe, it, expect, beforeAll } from 'vitest';
import { buildSamples, stampGeminiSparkle } from '../src/samples/samples.js';
import { scanBytes } from '../src/scan/engine.js';
import { cleanBlob } from '../src/clean/index.js';
import { planFor, ITEMS, outputName } from '../src/clean/catalog.js';
import { cleanTokens, cleanHidden, cleanAttribution } from '../src/clean/text.js';
import { removeSparkle } from '../src/clean/pixels.js';
import { openZip } from '../src/scan/zipreader.js';
import { decodePngRegion, pngSize } from '../src/scan/pngdecode.js';
import { jpegWithSegments, exifSegment, xmpSegment, proceduralRGBA, zip } from '../src/samples/builders.js';
import { SEED_JPEG_B64 } from '../src/samples/seed-jpeg.js';
import { decodeUtf8, encodeUtf8 } from '../src/lib/bytes.js';
import { writeZip } from '../src/lib/zipwrite.js';

const A = Object.keys(ITEMS).filter((k) => ITEMS[k].tier === 'A');
const ALL = Object.keys(ITEMS);
const ids = (n, o = []) => { for (const f of n.findings) if (f.strength !== 'info') o.push(f.id); for (const c of n.children || []) ids(c, o); return o; };
let S;
const clean = async (name, items) => {
  const s = S.find((x) => x.name === name);
  const c = await cleanBlob(new Blob([s.bytes]), s.name, { items });
  return { c, before: await scanBytes(s.bytes, s.name), after: await scanBytes(c.bytes, c.name), src: s.bytes };
};

beforeAll(async () => { S = await buildSamples(); }, 60_000);

describe('text cleaners', () => {
  it('removes citation tokens and AI tracking params but keeps other params', () => {
    const r = cleanTokens('Growth 【4†source】. See https://x.org/a?utm_source=chatgpt.com and https://y.org/b?id=7&utm_source=chatgpt.com&lang=en :contentReference[oaicite:0]{index=0}');
    expect(r.text).toBe('Growth. See https://x.org/a and https://y.org/b?id=7&lang=en');
    expect(r.n).toBe(4);
  });
  it('removes hidden characters but keeps BOM and emoji joiners', () => {
    const r = cleanHidden('﻿Hi​ there 👨‍👩 ok now');
    expect(r.text).toBe('﻿Hi there 👨‍👩 ok now');
  });
  it('removes AI attribution lines only', () => {
    const r = cleanAttribution('fix: bug\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n# Generated by GitHub Copilot\nx = 1\n');
    expect(r.text).toBe('fix: bug\n\nx = 1\n');
    expect(r.n).toBe(2);
  });
});

describe('planFor', () => {
  it('lists removable items, tiers and manual phrases', async () => {
    const r = await scanBytes(S.find((s) => s.name === 'market-report.docx').bytes, 'market-report.docx');
    const p = planFor(r);
    expect(p.items.map((i) => i.key)).toContain('tokens');
    expect(p.manual.length).toBeGreaterThan(0);
    expect(p.unremovable.some((u) => /Invisible/.test(u.label))).toBe(true);
  });
  it('names outputs with a -clean suffix', () => {
    expect(outputName('report.v2.docx')).toBe('report.v2-clean.docx');
    expect(outputName('photo.jpg', 'png')).toBe('photo-clean.png');
  });
});

describe('images', () => {
  it('PNG: prompts removed, pixels untouched', async () => {
    const { c, after, src } = await clean('sd-portrait.png', A);
    expect(ids(after)).not.toContain('prov.png.parameters');
    const s1 = pngSize(src), a = await decodePngRegion(src, 0, 0, s1.width, s1.height), b = await decodePngRegion(c.bytes, 0, 0, s1.width, s1.height);
    expect(Buffer.compare(Buffer.from(a.data), Buffer.from(b.data))).toBe(0);
  });

  it('JPEG: tier A keeps disclosure labels, tier B removes them, scan data byte-identical', async () => {
    const a = await clean('firefly-poster.jpg', A);
    expect(ids(a.after)).toContain('prov.iptc.trainedAlgorithmicMedia');
    expect(ids(a.after).some((i) => i.startsWith('meta.tool'))).toBe(false);
    const b = await clean('firefly-poster.jpg', ALL);
    expect(b.after.verdict).toBe('clean');
    const sos = (x) => x.subarray(x.findIndex((v, i) => v === 0xff && x[i + 1] === 0xda));
    expect(Buffer.compare(Buffer.from(sos(b.src)), Buffer.from(sos(b.c.bytes)))).toBe(0);
  });

  it('JPEG: keeps Orientation and camera data while removing Software', async () => {
    const seed = Uint8Array.from(atob(SEED_JPEG_B64), (ch) => ch.charCodeAt(0));
    const src = jpegWithSegments(seed, [exifSegment({ 0x010f: 'Canon', 0x0131: 'Midjourney v6' })]);
    const c = await cleanBlob(new Blob([src]), 'x.jpg', { items: ['fingerprints'] });
    const r = await scanBytes(c.bytes, 'x.jpg');
    expect(r.meta.exif.Make).toBe('Canon');
    expect(r.meta.exif.Software).toBeUndefined();
    expect(r.verdict).toBe('clean');
  });

  it('JPEG: China AIGC label needs tier B', async () => {
    expect(ids((await clean('doubao-poster.jpg', A)).after)).toContain('prov.tc260');
    expect((await clean('doubao-poster.jpg', ALL)).after.verdict).toBe('clean');
  });

  it('JPEG: XMP edits keep unrelated properties', async () => {
    const seed = Uint8Array.from(atob(SEED_JPEG_B64), (ch) => ch.charCodeAt(0));
    const src = jpegWithSegments(seed, [xmpSegment('<rdf:Description xmlns:xmp="http://ns.adobe.com/xap/1.0/" xmlns:dc="http://purl.org/dc/elements/1.1/" xmp:CreatorTool="DALL-E 3" xmp:Rating="4"/>')]);
    const c = await cleanBlob(new Blob([src]), 'x.jpg', { items: ['fingerprints'] });
    const text = decodeUtf8(c.bytes);
    expect(text).toContain('xmp:Rating="4"');
    expect(text).not.toContain('CreatorTool');
  });

  it('Gemini sparkle is removed and the corner restored', async () => {
    const W = 1024, H = 1024, orig = proceduralRGBA(W, H, 1.3);
    const wm = stampGeminiSparkle(Uint8Array.from(orig), W, H);
    expect(removeSparkle(wm, W, H).removed).toBe(true);
    let se = 0, n = 0;
    for (let y = H - 144; y < H - 96; y++) for (let x = W - 144; x < W - 96; x++) for (let k = 0; k < 3; k++) { const i = (y * W + x) * 4 + k; se += (wm[i] - orig[i]) ** 2; n++; }
    expect(10 * Math.log10(255 ** 2 / (se / n))).toBeGreaterThan(35);
    const { after } = await clean('gemini-sparkle.png', ALL);
    expect(ids(after)).not.toContain('watermark.gemini');
  });

  it('leaves the sparkle alone without tier B', async () => {
    const { c } = await clean('gemini-sparkle.png', A);
    expect(c.changed).toBe(false);
  });
});

describe('documents', () => {
  it('DOCX: tokens and tracking links removed, text preserved, assistant phrases reported', async () => {
    const { c, after } = await clean('market-report.docx', A);
    expect(ids(after)).not.toContain('artifact.oai-cite');
    expect(ids(after)).not.toContain('artifact.utm-ai');
    expect(c.report.manual.length).toBeGreaterThan(0);
    const z = await openZip(new Blob([c.bytes]));
    const body = decodeUtf8(await z.read(z.entries.find((e) => e.name === 'word/document.xml')));
    expect(body).toContain('a rich tapestry of trends emerges');
    expect(body).not.toContain('†');
  });

  it('XLSX: AI formulas become values and calcChain stays consistent', async () => {
    const { c, after } = await clean('q3-forecast.xlsx', A);
    expect(after.verdict).toBe('clean');
    const z = await openZip(new Blob([c.bytes]));
    const sheet = decodeUtf8(await z.read(z.entries.find((e) => e.name === 'xl/worksheets/sheet1.xml')));
    expect(sheet).not.toContain('COPILOT');
    expect(sheet).toContain('Strong growth driven by new accounts.');
    expect(sheet).toContain('<f>SUM(B2:B3)</f>');
  });

  it('PDF: Producer/Creator removed by a full rewrite, page text intact', async () => {
    const { c, after } = await clean('pitch-deck.pdf', A);
    expect(ids(after).some((i) => i.startsWith('meta.tool'))).toBe(false);
    expect(after.meta.pages).toBe(1);
    expect(after.meta.info?.Producer).toBeUndefined();
    expect(decodeUtf8(c.bytes)).not.toContain('Gamma');
    expect(c.report.manual.length + (ids(after).includes('artifact.as-an-ai') ? 1 : 0)).toBeGreaterThan(0);
  }, 30_000);
});

describe('archives', () => {
  it('drops AI config files and attribution only with tier B; nested archives survive', async () => {
    const a = await clean('weather-app-src.zip', A);
    expect(a.c.changed).toBe(false);
    const b = await clean('weather-app-src.zip', ALL);
    const z = await openZip(new Blob([b.c.bytes]));
    const names = z.entries.map((e) => e.name);
    expect(names).not.toContain('weather-app/.cursorrules');
    expect(names).toContain('weather-app/assets/archive.zip');
    const app = decodeUtf8(await z.read(z.entries.find((e) => e.name === 'weather-app/app.py')));
    expect(app).not.toMatch(/Generated by GitHub Copilot/);
    expect(app).toContain('def fetch_weather');
  });

  it('copies entries it cannot read byte-for-byte (pass-through)', async () => {
    const inner = zip([{ name: 'a.txt', data: 'hello' }]);
    const z1 = await openZip(new Blob([inner]));
    const e = z1.entries[0];
    const out = await writeZip([{ name: 'a.txt', passthrough: { data: await z1.readRaw(e), method: e.method, crc: e.crc, size: e.size, flags: e.flags } }]);
    const z2 = await openZip(new Blob([out]));
    expect(decodeUtf8(await z2.read(z2.entries[0]))).toBe('hello');
  });
});

describe('text files', () => {
  it('cleans code attribution and keeps a clean file unchanged', async () => {
    const src = encodeUtf8('// Generated by ChatGPT\nconst x = 1;​\n');
    const c = await cleanBlob(new Blob([src]), 'a.js', { items: ALL });
    expect(decodeUtf8(c.bytes)).toBe('const x = 1;\n');
    const keep = await cleanBlob(new Blob([encodeUtf8('plain text')]), 'b.txt', { items: ALL });
    expect(keep.changed).toBe(false);
  });
});
