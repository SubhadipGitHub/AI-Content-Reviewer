import { el, html, raw, on, $ } from '../lib/dom.js';
import { icon, VERDICT_ICON } from '../ui/icons.js';
import { store, saveSetting } from '../app/store.js';
import { VERDICTS } from '../scan/score.js';
import { RULES_VERSION } from '../scan/rules.js';
import { applyTheme, applyMotion } from '../ui/theme.js';
import { initAvatar, mountAvatar, avatarMode } from '../avatar/index.js';
import { startOnboarding } from '../ui/onboarding.js';
import { installState, promptInstall } from '../ui/install.js';

const DETECTS = [
  ['badge-check', 'Provenance & Content Credentials', 'Signed C2PA manifests and IPTC “Digital Source Type” labels that OpenAI, Adobe, Google, Microsoft and others embed in generated media.', ['C2PA / JUMBF manifests', 'IPTC trainedAlgorithmicMedia', 'IPTC AI system / prompt fields']],
  ['fingerprint', 'Generator fingerprints', 'Tool names and generation settings written into EXIF, XMP, PNG text chunks, PDF and Office properties.', ['Stable Diffusion / ComfyUI prompts & seeds', 'Midjourney, DALL·E, Firefly, Gemini…', 'Gamma, Copilot, ChatGPT in PDF/Office metadata']],
  ['bot', 'Chatbot residue', 'Text that only appears when an AI answer is pasted without editing.', ['ChatGPT 【4†source】 and oaicite tokens', 'utm_source=chatgpt.com links', '“As an AI language model…”, “I hope this helps!”']],
  ['eye', 'Hidden characters', 'Zero-width and other invisible Unicode characters used by some watermarking schemes.', ['Zero-width spaces & joiners', 'Narrow no-break spaces', 'Positions shown in evidence']],
  ['code-2', 'Code & repositories', 'Explicit attribution and AI-assistant configuration inside source code and archives.', ['Generated by Copilot / Claude Code', 'Co-Authored-By AI trailers', '.cursorrules, CLAUDE.md, copilot-instructions.md']],
  ['sheet', 'Spreadsheet AI functions', 'Cells computed by language models inside Excel and Sheets exports.', ['=COPILOT()', '=GPT(), =AI(), =OPENAI()', 'Comments by AI reviewers']],
  ['wand-2', 'Writing style (soft signal)', 'Statistical patterns typical of LLM prose. Never decisive on its own.', ['Low sentence-length variation', 'AI-favoured vocabulary (“delve”, “tapestry”)', 'Stock phrases and uniform structure']],
  ['layers', 'Deep inspection', 'Archives and documents are opened recursively, including embedded images.', ['ZIP up to 5 levels deep', 'Images inside DOCX/PPTX/XLSX', 'Zip-bomb and size guards']],
];

const VERDICT_TEXT = {
  strong: 'Hard identifiers such as signed credentials, generator metadata or chatbot residue.',
  likely: 'Several moderate signals agree, but no single piece of hard proof.',
  possible: 'Soft signals only (style, generic metadata). Review the evidence.',
  clean: 'Nothing found. AI content can still be stripped of identifiers.',
};

export function renderGuide(root) {
  const s = store.settings;
  const view = el(html`<div class="view">
    <div class="page-head"><div><h1>Guide & settings</h1><p>What Lens looks for, how to read results, and how to install the app.</p></div></div>

    <section class="section" style="margin-top:0">
      <div class="section-head"><h2>What gets detected</h2></div>
      <div class="grid-cards">${DETECTS.map(([ic, t, d, list]) => html`<article class="card feature"><div class="f-ic">${raw(icon(ic))}</div><h3>${t}</h3><p>${d}</p><ul>${list.map((x) => html`<li>${x}</li>`)}</ul></article>`)}</div>
    </section>

    <section class="section">
      <div class="section-head"><h2>Reading the verdict</h2></div>
      <div class="verdict-scale">${['strong', 'likely', 'possible', 'clean'].map((k) => html`<div class="card" data-tone="${VERDICTS[k].tone}"><span class="pill" data-tone="${VERDICTS[k].tone}">${raw(icon(VERDICT_ICON[k]))}${VERDICTS[k].label}</span><p>${VERDICT_TEXT[k]}</p></div>`)}</div>
      <div class="notice" data-tone="warning" style="margin-top:14px">${raw(icon('alert-triangle'))}<span><b>Signals, not proof.</b> Identifiers are easy to remove (screenshots, re-saving, copy-paste into a new file), so “No AI signals” never guarantees human authorship. Use the evidence to start a conversation, not to make accusations. Content Credentials signatures are recognised but not cryptographically verified offline.</span></div>
    </section>

    <section class="section">
      <div class="section-head"><h2>Settings</h2></div>
      <div class="card">
        <div class="setting"><div class="s-text"><b>Theme</b><span>Follow your device or pick one.</span></div>
          <div class="seg" data-setting="theme">${['system', 'light', 'dark'].map((v) => html`<button aria-pressed="${s.theme === v}" data-v="${v}">${v[0].toUpperCase() + v.slice(1)}</button>`)}</div></div>
        <div class="setting"><div class="s-text"><b>Mascot</b><span>3D needs WebGL; Simple is a lightweight animated drawing.</span></div>
          <div class="seg" data-setting="mascot">${[['3d', '3D'], ['simple', 'Simple'], ['off', 'Off']].map(([v, l]) => html`<button aria-pressed="${s.mascot === v}" data-v="${v}">${l}</button>`)}</div></div>
        <div class="setting"><div class="s-text"><b>Animations</b><span>Reduce motion across the app.</span></div>
          <div class="seg" data-setting="motion">${[['system', 'System'], ['reduce', 'Reduced']].map(([v, l]) => html`<button aria-pressed="${s.motion === v}" data-v="${v}">${l}</button>`)}</div></div>
        <div class="setting"><div class="s-text"><b>Keep files in Library</b><span>Store originals on this device so you can re-scan or download them later.</span></div>
          <button class="switch" role="switch" aria-checked="${!!s.keepFiles}" data-toggle="keepFiles" aria-label="Keep files in Library"></button></div>
        <div class="setting"><div class="s-text"><b>Onboarding</b><span>Replay the welcome tour.</span></div><button class="btn btn-sm" id="replay">${raw(icon('play'))}Replay</button></div>
      </div>
    </section>

    <section class="section">
      <div class="section-head"><h2>Install on any device</h2><div class="spacer"></div><button class="btn btn-primary btn-sm ${installState().canPrompt ? '' : 'hidden'}" id="g-install">${raw(icon('download'))}Install now</button></div>
      <div class="install-grid">
        <div class="card"><h3>${raw(icon('monitor'))} Windows · macOS · Linux</h3><ol><li>Open this page in Chrome, Edge or Brave.</li><li>Click <b>Install</b> in the header (or the install icon in the address bar).</li><li>Launch it from your Start menu, Dock or app list — works offline.</li></ol></div>
        <div class="card"><h3>${raw(icon('smartphone'))} iPhone & iPad</h3><ol><li>Open in Safari.</li><li>Tap <b>Share</b> → <b>Add to Home Screen</b>.</li><li>Open Lens from your Home Screen.</li></ol></div>
        <div class="card"><h3>${raw(icon('smartphone'))} Android</h3><ol><li>Open in Chrome.</li><li>Tap <b>Install app</b> (or ⋮ → <b>Add to Home screen</b>).</li><li>Find it in your app drawer.</li></ol></div>
        <div class="card"><h3>${raw(icon('file-code'))} Single-file download</h3><ol><li>Download <b>AI-Content-Reviewer.html</b> from the GitHub Releases page.</li><li>Double-click to open — no install, no internet.</li><li>Great for locked-down or air-gapped machines.</li></ol></div>
      </div>
    </section>

    <section class="section">
      <div class="section-head"><h2>Privacy</h2></div>
      <div class="card" style="padding:18px;display:grid;gap:10px;color:var(--text-2);font-size:.9rem">
        <p>${raw(icon('lock', 'inline'))} Files are read by your browser on your device. Nothing is uploaded, there is no account, no analytics and no tracking.</p>
        <p>Stored files and results live in this browser's IndexedDB. Clear them any time from the Library.</p>
        <p class="muted" style="font-size:.8rem">Detection rules ${RULES_VERSION} · <a href="https://github.com/SubhadipGitHub/AI-Content-Reviewer" target="_blank" rel="noopener">Source on GitHub ${raw(icon('external-link', 'inline'))}</a></p>
      </div>
    </section>
  </div>`);
  root.replaceChildren(view);
  mountAvatar(null);

  on(view, 'click', '[data-setting] button', async (e, b) => {
    const key = b.closest('[data-setting]').dataset.setting;
    const v = b.dataset.v;
    for (const x of b.parentElement.children) x.setAttribute('aria-pressed', String(x === b));
    await saveSetting(key, v);
    if (key === 'theme') applyTheme(v);
    if (key === 'motion') { applyMotion(v); await initAvatar(store.settings.mascot); }
    if (key === 'mascot') { await initAvatar(v); mountAvatar(null); if (v === '3d' && avatarMode() !== '3d') b.parentElement.insertAdjacentHTML('afterend', '<span class="muted" style="font-size:.75rem;margin-left:8px">3D unavailable — using Simple</span>'); }
  });
  on(view, 'click', '[data-toggle]', async (e, b) => {
    const on_ = b.getAttribute('aria-checked') !== 'true';
    b.setAttribute('aria-checked', String(on_));
    await saveSetting(b.dataset.toggle, on_);
  });
  $('#replay', view).addEventListener('click', () => { location.hash = '#/'; setTimeout(() => startOnboarding(), 300); });
  $('#g-install', view)?.addEventListener('click', promptInstall);
  return () => {};
}
