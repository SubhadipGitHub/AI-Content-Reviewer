// Maps scan findings to removal options. Shared by the UI (checklist) and the cleaner.

/** Removal items. Tier A = clean-up; tier B = disclosure labels (needs acknowledgment). */
export const ITEMS = {
  tokens: { tier: 'A', label: 'Chatbot citation tokens & AI tracking links', hint: '【4†source】, oaicite tokens, utm_source=chatgpt.com' },
  hidden: { tier: 'A', label: 'Hidden Unicode characters', hint: 'Zero-width spaces, joiners and similar' },
  prompts: { tier: 'A', label: 'Prompts & generation settings', hint: 'Stable Diffusion / ComfyUI / Midjourney parameters' },
  fingerprints: { tier: 'A', label: 'Generator & software names', hint: 'Software, CreatorTool, Producer, Application, HTML generator' },
  formulas: { tier: 'A', label: 'AI spreadsheet formulas → values', hint: '=COPILOT(), =GPT()… replaced by their results' },
  private: { tier: 'A', label: 'Personal metadata', hint: 'Authors, GPS, serial numbers, comments', optional: true },
  c2pa: { tier: 'B', label: 'Content Credentials (C2PA)', hint: 'Signed provenance manifests' },
  labels: { tier: 'B', label: 'AI disclosure labels', hint: 'IPTC DigitalSourceType, "Made with Google AI", AI document labels' },
  tc260: { tier: 'B', label: 'China AIGC labels (GB 45438-2025)', hint: 'TC260 AIGC metadata' },
  aiAuthors: { tier: 'B', label: 'AI author & reviewer names', hint: 'Copilot / ChatGPT as author or commenter' },
  attribution: { tier: 'B', label: 'AI attribution in code', hint: '"Generated by Copilot", Co-Authored-By trailers' },
  repoFiles: { tier: 'B', label: 'AI assistant config files', hint: '.cursorrules, CLAUDE.md, AGENTS.md…' },
  sparkle: { tier: 'B', label: 'Visible Gemini watermark', hint: 'Restores the pixels under the ✦ sparkle' },
};

const MANUAL = new Set(['artifact.as-an-ai', 'artifact.knowledge-cutoff', 'artifact.chat-ui', 'artifact.assistant-opener', 'artifact.assistant-closer', 'artifact.placeholder', 'artifact.meta-prompt']);

/** Which removal item clears a finding (null = cannot be removed automatically). */
export function itemFor(f, node) {
  const id = f.id;
  if (/^artifact\.(oai-cite|oai-contentref|oai-entity|utm-ai)$/.test(id)) return node.kind === 'pdf' && id !== 'artifact.utm-ai' ? null : 'tokens';
  if (id === 'hidden.unicode') return node.kind === 'pdf' ? null : 'hidden';
  if (id.startsWith('prov.png.')) return 'prompts';
  if (id.startsWith('prov.iptc.')) return 'labels';
  if (id.startsWith('prov.c2pa.')) return node.kind === 'image' && /^(png|jpeg|webp)$/.test(node.format) || node.kind === 'pdf' ? 'c2pa' : null;
  if (id === 'prov.tc260') return 'tc260';
  if (id === 'watermark.gemini') return 'sparkle';
  if (id === 'formula.ai') return 'formulas';
  if (id === 'meta.ai-label' || id === 'meta.custom-ai') return 'labels';
  if (id.startsWith('meta.person.') || id === 'meta.ai-reviewer') return 'aiAuthors';
  if (id === 'meta.grok' || id.startsWith('meta.scripted.')) return 'fingerprints';
  if (id.startsWith('meta.text.')) return /parameters|prompt|job id|workflow|settings/i.test(f.title) ? 'prompts' : /label/i.test(f.title) ? 'labels' : 'fingerprints';
  if (id.startsWith('meta.tool.')) return /^Credit:/.test(f.detail || '') ? 'labels' : 'fingerprints';
  if (id.startsWith('code.') && id !== 'code.style') return 'attribution';
  if (id.startsWith('repo.')) return 'repoFiles';
  return null;
}

const FORMAT_NOTES = {
  sparkle: 'Removing the visible watermark re-encodes the image (lossless PNG for PNG files, high-quality JPEG/WebP otherwise) and drops all other metadata.',
  keepC2pa: 'This file has Content Credentials. Any other change will make their signature show as tampered.',
};

/**
 * Build the checklist for one or more scan results.
 * @returns {{ items: {key, tier, label, hint, count, files}[], manual: {label, text, where}[], unremovable: {label, why}[], notes: string[] }}
 */
export function planFor(results) {
  const list = Array.isArray(results) ? results : [results];
  const counts = new Map();
  const manual = [];
  const unremovable = new Map();
  let hasC2pa = false, hasImage = false, hasDoc = false;
  const walk = (node, root) => {
    if (node.kind === 'image') hasImage = true;
    if (node.kind === 'document' || node.kind === 'pdf') hasDoc = true;
    for (const f of node.findings || []) {
      if (f.strength === 'info' && !f.id.startsWith('prov.c2pa')) continue;
      if (f.id.startsWith('prov.c2pa')) hasC2pa = true;
      if (MANUAL.has(f.id)) { manual.push({ label: f.title, text: f.evidence?.[0]?.text?.slice(0, 90) || '', where: `${root.name}${node !== root ? ` › ${node.name}` : ''} · ${f.location || ''}` }); continue; }
      const key = itemFor(f, node);
      if (key) {
        const c = counts.get(key) || { count: 0, files: new Set() };
        c.count++; c.files.add(root.name);
        counts.set(key, c);
      } else {
        const why = f.id === 'style.llm' ? 'Writing style is part of the text itself.'
          : f.id === 'code.style' ? 'Coding style is part of the code itself.'
          : f.id === 'watermark.dalle' ? 'The colour bar covers the pixels underneath; crop it out manually.'
          : f.id === 'meta.dimensions' ? 'Image size is not metadata.'
          : f.id.startsWith('artifact.') || f.id === 'hidden.unicode' ? 'Text inside PDF pages can\'t be edited safely.'
          : 'Not supported for this file type.';
        unremovable.set(f.title, { label: f.title, why });
      }
    }
    for (const c of node.children || []) walk(c, root);
  };
  for (const r of list) walk(r, r);
  if (hasImage || hasDoc) {
    if (!counts.has('private')) counts.set('private', { count: 0, files: new Set() });
  }
  const notes = [];
  if (counts.has('sparkle')) notes.push(FORMAT_NOTES.sparkle);
  if (hasC2pa) notes.push(FORMAT_NOTES.keepC2pa);
  unremovable.set('Invisible watermarks', { label: 'Invisible watermarks (SynthID, Meta, OpenAI)', why: 'Hidden in the pixels; only their owners can read them.' });
  const items = Object.entries(ITEMS)
    .filter(([k]) => counts.has(k))
    .map(([k, v]) => ({ key: k, ...v, count: counts.get(k).count, files: [...counts.get(k).files] }));
  return { items, manual: manual.slice(0, 30), unremovable: [...unremovable.values()], notes };
}

export const outputName = (name, ext) => {
  const i = name.lastIndexOf('.');
  const base = i > 0 ? name.slice(0, i) : name;
  const e = ext || (i > 0 ? name.slice(i + 1) : '');
  return `${base}-clean${e ? `.${e}` : ''}`;
};
